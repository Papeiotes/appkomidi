export type MessageKey = keyof typeof messages;

export function translateError(locale: Locale, code: string): string {
  if (code in messages) return t(locale, code as MessageKey);
  return t(locale, "REQUEST_FAILED");
}

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const entry = messages[key];
  let text: string = entry[locale] ?? entry.en;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function formatWhen(iso: string | Date, locale: Locale): string {
  const date = typeof iso === "string" ? new Date(iso) : iso;
  return new Intl.DateTimeFormat(locale === "el" ? "el-GR" : "en-GB", {
    weekday: "short",
    day: "numeric",
    month: "short",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
}

export function formatMeters(meters: number, locale: Locale): string {
  const rounded = Math.round(meters);
  if (rounded < 1000) return t(locale, "metersAway", { m: rounded });
  const km = (rounded / 1000).toFixed(1);
  return locale === "el" ? `${km} χλμ.` : `${km} km`;
}
